// Command levels measures every factory preset and writes synth/levels.go, a table of master
// volumes that makes them all about equally loud.
//
//	go run ./tools/levels
package main

import (
	"fmt"
	"math"
	"os"
	"strings"

	"github.com/codypowpow-afk/wavebass/synth"
)

func measure(e *synth.Engine, p *synth.Preset) (peak, win float64) {
	patch := p.Patch
	patch[synth.PVolume] = 0.7
	e.Panic()
	e.Process(make([]float32, 2*synth.SampleRate/2))
	e.LoadPatch(&patch)
	notes := []int{31}
	if patch[synth.PMode] == 0 {
		notes = []int{31, 38, 43}
	}
	for _, n := range notes {
		e.KeyDown(n, 0.85)
	}
	buf := make([]float32, 2*synth.SampleRate*3/2)
	e.Process(buf)
	for _, n := range notes {
		e.KeyUp(n)
	}
	const w = 2 * 2400 // 50 ms windows
	for i := 0; i+w <= len(buf); i += w {
		var s float64
		for _, v := range buf[i : i+w] {
			s += float64(v) * float64(v)
			peak = math.Max(peak, math.Abs(float64(v)))
		}
		win = math.Max(win, math.Sqrt(s/w))
	}
	return
}

func main() {
	e := synth.NewEngine()
	var b strings.Builder
	b.WriteString("// Code generated by tools/levels; DO NOT EDIT.\n\npackage synth\n\n// presetVol is the master volume that brings each factory preset to the same loudness.\nvar presetVol = map[string]float64{\n")
	for i := range synth.Presets {
		p := &synth.Presets[i]
		peak, win := measure(e, p)
		g := math.Min(0.30/win, 0.80/peak)
		vol := math.Min(1, 0.7*math.Sqrt(g))
		fmt.Fprintf(&b, "\t%q: %.3f,\n", p.Name, vol)
		fmt.Printf("%-16s peak %.2f win %.3f -> vol %.2f\n", p.Name, peak, win, vol)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("synth/levels.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
